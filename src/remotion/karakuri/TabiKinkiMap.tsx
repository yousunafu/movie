export const kmapXY = (lon: number, lat: number): [number, number] => [
  KMAP.x0 + (lon - KMAP.lon0) * (KMAP.w / (KMAP.lon1 - KMAP.lon0)),
  KMAP.y0 + (KMAP.lat1 - lat) * (KMAP.h / (KMAP.lat1 - KMAP.lat0)),
];

type LL = [number, number];
const poly = (pts: LL[]): string =>
  "M " + pts.map(([lo, la]) => kmapXY(lo, la).map((v) => v.toFixed(1)).join(" ")).join(" L ") + " Z";
const line = (pts: LL[]): string =>
  "M " + pts.map(([lo, la]) => kmapXY(lo, la).map((v) => v.toFixed(1)).join(" ")).join(" L ");

