/** 緯度経度の折れ線 → 閉じた path 文字列 */
const poly = (pts: LL[], dlon = 0, dlat = 0): string =>
  "M " +
  pts.map(([lon, lat]) => {
    const [x, y] = iwxy(lon + dlon, lat + dlat);
    return `${x.toFixed(1)} ${y.toFixed(1)}`;
  }).join(" L ") +
  " Z";

/** 緯度経度の折れ線 → 開いた path 文字列 */
