// ===== 街道名の札 (画面座標でそのまま置く。ズームの外に出して文字サイズを一定に保つ) =====
export const KaidoLabel: React.FC<{
  x: number; y: number; text: string; color: string; size?: number; t?: number;
  tailTo?: [number, number]; sub?: boolean;
}> = ({ x, y, text, color, size = 32, t = 1, tailTo, sub = false }) => {
  if (t <= 0) return null;
  // 札の幅は「文字数 × fontSize + 余白」。日本語は全角なので字送り = fontSize でよい。
  const w = text.length * size + (sub ? 22 : 30);
  const h = size * (sub ? 1.6 : 1.7);
  return (
    <g opacity={Math.min(t, 1)}>
      {tailTo && (
        <line x1={x} y1={y} x2={tailTo[0]} y2={tailTo[1]} stroke={color}
          strokeWidth={sub ? 2.6 : 3.5} strokeDasharray={sub ? "6 6" : "8 7"}
          opacity={sub ? 0.7 : 0.85} />
      )}
      <rect x={x - w / 2} y={y - h / 2} width={w} height={h} rx={9}
        fill={KRP.white} stroke={color} strokeWidth={sub ? 3 : 4.5} opacity={sub ? 0.97 : 1} />
      <text x={x} y={y + size * 0.36} textAnchor="middle" fontFamily={FONT}
        fontWeight={sub ? 700 : 900} fontSize={size} fill={color}>{text}</text>
    </g>
  );
};

