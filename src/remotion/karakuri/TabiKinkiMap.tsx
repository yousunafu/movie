// 地図上の小さな地名札 (海や空きの側に逃がす)
export const KmapLabel: React.FC<{
  lon: number; lat: number; text: string; dx?: number; dy?: number; t?: number; accent?: boolean;
}> = ({ lon, lat, text, dx = -110, dy = 0, t = 1, accent = false }) => {
  if (t <= 0) return null;
  const [px, py] = kmapXY(lon, lat);
  const size = accent ? 30 : 26;
  const w = text.length * size * 1.02 + 26;
  const cx = px + dx, cy = py + dy;
  return (
    <g opacity={Math.min(t, 1)}>
      <line x1={px} y1={py} x2={cx + (dx < 0 ? w / 2 : -w / 2)} y2={cy}
        stroke={KRP.ink} strokeWidth={3} opacity={0.55} />
      <circle cx={px} cy={py} r={accent ? 11 : 8} fill={accent ? KRP.red : KRP.white}
        stroke={KRP.ink} strokeWidth={4} />
      <rect x={cx - w / 2} y={cy - size * 0.86} width={w} height={size * 1.72} rx={8}
        fill={KRP.white} stroke={KRP.ink} strokeWidth={accent ? 4.5 : 3.5} />
      <text x={cx} y={cy + size * 0.36} textAnchor="middle" fontFamily={FONT}
        fontWeight={900} fontSize={size} fill={accent ? KRP.red : KRP.ink}>{text}</text>
    </g>
  );
};
