// 声の緩急 (長尺対策)。文の種類ごとにVOICEVOXの話速・間・抑揚を変えて、
// 20分聴いても単調にならないようにする。字幕は原文のまま (読み上げだけ変わる)。

import { VOICE } from "../channel";

export type VoiceStyle = {
  speedScale: number;
  prePhonemeLength: number; // 文頭の静寂 (秒)
  postPhonemeLength: number; // 文末の静寂 (秒)
  intonationScale: number; // 抑揚 (1.0が標準)
  /** この文だけ別の声で喋らせる (省略時は VOICE.voicevoxSpeaker)。sekai の反応役で使う */
  speaker?: string;
  /** 上の声のスタイル名 (省略時は VOICE.voicevoxStyle) */
  speakerStyle?: string;
};

const base = () => VOICE.voicevoxSpeed;

export function voiceStyleFor(
  text: string,
  type: string,
  motif: string,
  isEnding = false,
): VoiceStyle {
  // 反応役 (sekai の新人記者) は別の声。行まるごとが「」の文に assign.ts が
  // type:"character" を付けているので、それを目印にする。
  // ★ 他の作風の character シーンまで巻き込まないよう、motif で sekai に限定する。
  if (type === "character" && /^sekai_/.test(motif)) {
    return {
      speedScale: VOICE.reactionSpeed,
      prePhonemeLength: 0.12,
      postPhonemeLength: 0.4,
      intonationScale: VOICE.reactionIntonation,
      speaker: VOICE.reactionSpeaker,
      speakerStyle: VOICE.reactionStyle,
    };
  }
  // 章扉: ゆっくり宣言し、前後にしっかり間を取る (場面転換の呼吸)
  if (type === "card" && motif === "chapter") {
    return {
      speedScale: base() * 0.95,
      prePhonemeLength: 0.4,
      postPhonemeLength: 0.7,
      intonationScale: 1.0,
    };
  }
  // 結論カード・締めの挨拶: 少しゆっくり + 文末に余韻
  if (type === "card" || isEnding) {
    return {
      speedScale: base() * 0.97,
      prePhonemeLength: 0.15,
      postPhonemeLength: 0.5,
      intonationScale: 1.05,
    };
  }
  // 感嘆・ひらめきの相づち (「おっ、頭いい。」など): 元気よく速め + 抑揚強め
  if (/^(おっ|おお|お見事|なるほど)、/.test(text.trim())) {
    return {
      speedScale: base() * 1.06,
      prePhonemeLength: 0.05,
      postPhonemeLength: 0.3,
      intonationScale: 1.2,
    };
  }
  // 問いかけ: ゆっくり + 抑揚強め + 視聴者が考える間
  if (/か[。？?]?$/.test(text.trim())) {
    return {
      speedScale: base() * 0.95,
      prePhonemeLength: 0.1,
      postPhonemeLength: 0.5,
      intonationScale: 1.1,
    };
  }
  // 通常の文
  return {
    speedScale: base(),
    prePhonemeLength: 0.1,
    postPhonemeLength: 0.15,
    intonationScale: 1.0,
  };
}

