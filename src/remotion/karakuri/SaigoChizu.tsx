// ===================================================================
// 世界の地形 (経度・緯度) と、それを地球儀/平面地図に落とす道具
// -------------------------------------------------------------------
// なぜ作ったか:
//   地球儀や世界地図を「それっぽい塊」で描くと、見る人にはすぐ嘘だと分かる。
//   海岸線を経度・緯度の実データで持ち、投影の式で描けば、
//   どのシーンでも同じ地球が出る (大陸の形も位置も食い違わない)。
// 使い方:
//   地球儀 = <ChikyuGi cx cy r lon0 .../>  (正射図法・赤道正面 + 見た目の傾き)
//   平面地図 = makeHeimen() で投影を作り、<HeimenRiku proj .../> と heimenTen() で点を置く
// 座標は [経度(東が+), 緯度(北が+)]。線の順は海岸をたどる順。
// ===================================================================

