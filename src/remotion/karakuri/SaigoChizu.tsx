// ===================================================================
// 地球儀 (正射図法・赤道正面)
//   x =  r * cos(緯度) * sin(経度 - 中心経度)
//   y = -r * sin(緯度)
//   見えるのは cos(緯度) * cos(経度 - 中心経度) > 0 の側だけ。
//   この向きなら緯線はまっすぐな横線、経線は半楕円になるので、線を正確に引ける。
//   地軸の傾きは、球ごと rotate するだけ (回しても正射図法のままなので嘘にならない)。
// ===================================================================
const toXY = (p: LonLat, r: number, lon0: number): [number, number, number] => {
  const la = p[1] * D;
  const dl = (p[0] - lon0) * D;
  return [r * Math.cos(la) * Math.sin(dl), -r * Math.sin(la), Math.cos(la) * Math.cos(dl)];
};

// 水平線 (見える/見えないの境) に乗せ直した点
const onRim = (ax: number, ay: number, r: number): [number, number] => {
  const d = Math.hypot(ax, ay) || 1;
  return [(ax / d) * r, (ay / d) * r];
};

// ひとつの海岸線を、見えている部分だけの path 文字列にする
const globePath = (pts: LonLat[], r: number, lon0: number): string => {
  const proj = pts.map((p) => toXY(p, r, lon0));
  let d = "";
  let open = false;
  for (let i = 0; i < proj.length; i++) {
    const [x, y, v] = proj[i];
    const prev = proj[(i - 1 + proj.length) % proj.length];
    if (v > 0) {
      if (!open) {
        if (prev[2] <= 0) {
          const [rx, ry] = onRim((x + prev[0]) / 2, (y + prev[1]) / 2, r);
          d += `M ${rx.toFixed(1)} ${ry.toFixed(1)} L ${x.toFixed(1)} ${y.toFixed(1)} `;
        } else {
          d += `M ${x.toFixed(1)} ${y.toFixed(1)} `;
        }
        open = true;
      } else {
        d += `L ${x.toFixed(1)} ${y.toFixed(1)} `;
      }
    } else if (open) {
      const [rx, ry] = onRim((x + prev[0]) / 2, (y + prev[1]) / 2, r);
      d += `L ${rx.toFixed(1)} ${ry.toFixed(1)} Z `;
      open = false;
    }
  }
  if (open) d += "Z ";
  return d;
};

export const ChikyuGi: React.FC<{
  cx: number; cy: number; r: number;
  lon0: number;            // 正面に来る経度
  tilt?: number;           // 地軸の傾き (見た目)
  sea: string; land: string; ink: string;
  grid?: string;           // 経緯線の色 (省略で描かない)
  landWidth?: number;
  children?: React.ReactNode; // 球の上に重ねるもの (航路など。球の中心が原点)
}> = ({ cx, cy, r, lon0, tilt = 0, sea, land, ink, grid, landWidth = 4, children }) => {
  // 緯線: 30度ごと。横棒の長さは cos(緯度)
  const parallels = [-60, -30, 0, 30, 60];
  // 経線: 30度ごと。半楕円の横半径は |sin(経度差)|
  const meridians = [0, 30, 60, 90, 120, 150, 180, 210, 240, 270, 300, 330];
  return (
    <g transform={`translate(${cx} ${cy}) rotate(${tilt})`}>
      <circle cx={0} cy={0} r={r} fill={sea} stroke={ink} strokeWidth={8} />
      <g>
        {WORLD.map((poly, i) => {
          const d = globePath(poly, r, lon0);
          if (!d) return null;
          return <path key={i} d={d} fill={land} stroke={ink} strokeWidth={landWidth}
            strokeLinejoin="round" />;
        })}
      </g>
      {grid && (
        <g fill="none" stroke={grid} strokeWidth={3} opacity={0.55}>
          {parallels.map((la) => {
            const w = r * Math.cos(la * D);
            const y = -r * Math.sin(la * D);
            return <line key={`p${la}`} x1={-w} y1={y} x2={w} y2={y}
              strokeWidth={la === 0 ? 4.5 : 3} />;
          })}
          {meridians.map((lo) => {
            const dl = ((lo - lon0 + 540) % 360) - 180;   // -180..180
            if (Math.abs(Math.abs(dl) - 90) < 0.5) {
              return <line key={`m${lo}`} x1={0} y1={-r} x2={0} y2={r} />;
            }
            const a = Math.abs(r * Math.sin(dl * D));
            const sweep = dl > 0 ? 1 : 0;
            return <path key={`m${lo}`}
              d={`M 0 ${-r} A ${a.toFixed(1)} ${r} 0 0 ${sweep} 0 ${r}`} />;
          })}
          <circle cx={0} cy={0} r={r} />
        </g>
      )}
      {children}
    </g>
  );
};

// 球の上に、好きな陸地だけを別の色で塗り直すための path (ChikyuGi の children で使う)
export const chikyuPath = (pts: LonLat[], r: number, lon0: number): string =>
  globePath(pts, r, lon0);

// 地球儀の上の一点 (札や航路を置くため)。裏側なら null
export const chikyuTen = (
  lon: number, lat: number, r: number, lon0: number,
): [number, number] | null => {
  const [x, y, v] = toXY([lon, lat], r, lon0);
  return v > 0 ? [x, y] : null;
};

// ===================================================================
// 平面地図 (正距円筒図法。基準緯度で横をちぢめるので形がゆがまない)
// ===================================================================
export type Heimen = {
  x: (lon: number) => number;
  y: (lat: number) => number;
};

export const makeHeimen = (opt: {
  lonMin: number; lonMax: number; latMin: number; latMax: number;
  x0: number; y0: number; w: number; h: number;
}): Heimen => {
  const latMid = (opt.latMin + opt.latMax) / 2;
  const ky = opt.h / (opt.latMax - opt.latMin);
  const kx = ky * Math.cos(latMid * D);
  const wUsed = (opt.lonMax - opt.lonMin) * kx;
  const left = opt.x0 + (opt.w - wUsed) / 2;
  return {
    x: (lon: number) => left + (lon - opt.lonMin) * kx,
    y: (lat: number) => opt.y0 + (opt.latMax - lat) * ky,
  };
};

export const heimenPath = (pts: LonLat[], m: Heimen): string =>
  pts.map((p, i) => `${i === 0 ? "M" : "L"} ${m.x(p[0]).toFixed(1)} ${m.y(p[1]).toFixed(1)}`)
    .join(" ") + " Z";

export const HeimenRiku: React.FC<{
  m: Heimen; set?: LonLat[][]; land: string; ink: string; width?: number;
}> = ({ m, set = EUROPE_SET, land, ink, width = 5 }) => (
  <g fill={land} stroke={ink} strokeWidth={width} strokeLinejoin="round">
    {set.map((poly, i) => <path key={i} d={heimenPath(poly, m)} />)}
  </g>
);
