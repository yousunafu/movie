// ===================================================================
// 旗 (出発点と到着点の印)
// ===================================================================
const FlagPin: React.FC<{
  x: number; y: number; t: number; color: string; wave: number; mark?: "circle" | "star";
}> = ({ x, y, t, color, wave, mark = "circle" }) => {
  const s = clamp01(t);
  if (s <= 0) return null;
  const flap = Math.sin(wave) * 4;
  return (
    <g transform={`translate(${x} ${y})`} opacity={s}>
      {/* 地面の印 */}
      <circle cx={0} cy={0} r={20} fill={color} opacity={0.2} />
      <circle cx={0} cy={0} r={11} fill={color} stroke={KRP.ink} strokeWidth={3.5} />
      {/* 竿 */}
      <path d={`M 0 -4 L 0 ${-66 * s}`} stroke={KRP.ink} strokeWidth={5} strokeLinecap="round" />
      {/* 旗 */}
      <path
        d={`M 2 ${-66 * s} L ${56 * s} ${-60 * s + flap} L ${52 * s} ${-36 * s + flap} L 2 ${-40 * s} Z`}
        fill={color}
        stroke={KRP.ink}
        strokeWidth={3.5}
      />
      {mark === "star" ? (
        <path
          d="M 24 -56 L 28 -49 L 36 -48 L 30 -43 L 32 -36 L 24 -40 L 16 -36 L 18 -43 L 12 -48 L 20 -49 Z"
          fill={KRP.white}
          opacity={0.95}
          transform={`scale(${s}) translate(0 ${flap * 0.4})`}
        />
      ) : (
        <circle cx={28 * s} cy={-48 * s + flap * 0.4} r={8 * s} fill={KRP.white} opacity={0.9} />
      )}
    </g>
  );
};

// ===================================================================
// 札 (地図の上に置く小さな木札。TagPlate とは別で、地図の中の地名用)
// ===================================================================
const MapLabel: React.FC<{
  x: number; y: number; text: string; t: number; size?: number; color?: string;
}> = ({ x, y, text, t, size = 38, color = KRP.ink }) => {
  const s = clamp01(t);
  if (s <= 0) return null;
  const w = text.length * size * 0.92 + 30;
  return (
    <g transform={`translate(${x} ${y})`} opacity={s}>
      <rect x={-w / 2 + 5} y={-size * 0.72 + 5} width={w} height={size * 1.44}
        rx={7} fill="#8D7A58" opacity={0.3} />
      <rect x={-w / 2} y={-size * 0.72} width={w} height={size * 1.44} rx={7}
        fill={MC.paper} stroke={KRP.ink} strokeWidth={4} />
      <text x={0} y={size * 0.34} textAnchor="middle" fontWeight={900}
        fontFamily="'Hiragino Maru Gothic ProN','Hiragino Sans',sans-serif"
        fontSize={size} fill={color}>{text}</text>
    </g>
  );
};

// ===================================================================
// 世界地図ぜんたい。
// 江戸 (右) → アテネ (左) へ、太い航路の弧が f に合わせて伸びていく。
// ===================================================================
export const IchiB5WorldMap: React.FC<{ f: number }> = ({ f }) => {
  const drawn = easeOut(clamp01(seg(f, 1, 20))); // 海岸線の内側の記号が引かれる
  const route = easeOut(clamp01(seg(f, 6, 34))); // 航路が伸びる
  const land = clamp01(seg(f, 22, 38)); // 到着点で何かが起きる気配

  const [ex, ey] = iwxy(IW_EDO[0] + JP_DLON, IW_EDO[1] + JP_DLAT); // 日本と同じだけずらす
  const [ax, ay] = iwxy(IW_ATHENS[0], IW_ATHENS[1]);

  // 航路の弧 (江戸 → アテネ。南まわりではなく大きく上へ張った弧で、画面を横断させる)
  // 弧の頂はおよそ y≈240 (紙の上端100より十分内側)
  const cx1 = ex - (ex - ax) * 0.28;
  const cy1 = ey - 240;
  const cx2 = ax + (ex - ax) * 0.28;
  const cy2 = ay - 255;
  // ベジェを route だけ進んだ点と接線 (矢印の位置と向き)
  const bez = (t: number) => {
    const u = 1 - t;
    const px = u * u * u * ex + 3 * u * u * t * cx1 + 3 * u * t * t * cx2 + t * t * t * ax;
    const py = u * u * u * ey + 3 * u * u * t * cy1 + 3 * u * t * t * cy2 + t * t * t * ay;
    const dx = 3 * u * u * (cx1 - ex) + 6 * u * t * (cx2 - cx1) + 3 * t * t * (ax - cx2);
    const dy = 3 * u * u * (cy1 - ey) + 6 * u * t * (cy2 - cy1) + 3 * t * t * (ay - cy2);
    return { px, py, rot: (Math.atan2(dy, dx) * 180) / Math.PI };
  };
  const head = bez(clamp01(route));
  const ROUTE_LEN = 1000; // pathLength で正規化する長さ (実長ではない)

  return (
    <g>
      {/* 机の天板 */}
      <rect x={0} y={0} width={1920} height={1080} fill="#B9A581" />
      {[0, 1, 2, 3, 4, 5, 6, 7].map((i) => (
        <path key={i}
          d={`M -40 ${60 + i * 140} C 576 ${40 + i * 140} 1344 ${90 + i * 140} 1960 ${55 + i * 140}`}
          stroke="#8D7A58" strokeWidth={2} fill="none" opacity={0.3} />
      ))}

      {/* 古地図の紙 = 海 */}
      <rect x={SHEET.x + 10} y={SHEET.y + 14} width={SHEET.w} height={SHEET.h}
        fill="#8D7A58" opacity={0.28} />
      <rect x={SHEET.x} y={SHEET.y} width={SHEET.w} height={SHEET.h}
        fill={MC.sea} stroke={MC.paperEdge} strokeWidth={3} />

      <defs>
        <clipPath id="ib5wmSheet">
          <rect x={SHEET.x} y={SHEET.y} width={SHEET.w} height={SHEET.h} />
        </clipPath>
      </defs>

      <g clipPath="url(#ib5wmSheet)">
        {/* 緯線・経線 (10度ごと) */}
        <g stroke={MC.line} strokeWidth={1.8} opacity={0.26} fill="none">
          {Array.from({ length: 10 }).map((_, i) => {
            const lat = 70 - i * 10;
            const [, y] = iwxy(0, lat);
            return <line key={`p${i}`} x1={SHEET.x} y1={y} x2={SHEET.x + SHEET.w} y2={y} />;
          })}
          {Array.from({ length: 18 }).map((_, i) => {
            const lon = -20 + i * 10;
            const [x] = iwxy(lon, 0);
            return <line key={`m${i}`} x1={x} y1={SHEET.y} x2={x} y2={SHEET.y + SHEET.h} />;
          })}
        </g>
        {/* 赤道 (少し濃く) */}
        <line x1={SHEET.x} y1={iwxy(0, 0)[1]} x2={SHEET.x + SHEET.w} y2={iwxy(0, 0)[1]}
          stroke={MC.line} strokeWidth={3} opacity={0.4} strokeDasharray="14 10" />

        {/* 海の波 */}
        <g stroke={MC.line} strokeWidth={2.6} opacity={0.34} fill="none" strokeLinecap="round">
          {SEA_WAVES.map(([lon, lat], i) => {
            const [x, y] = iwxy(lon, lat);
            const sway = Math.sin(f / 18 + i) * 2.2;
            return (
              <path key={i} d={`M ${x - 26 + sway} ${y} q 13 -8 26 0 q 13 8 26 0`} />
            );
          })}
        </g>

        {/* 紙の斑 */}
        <g fill={MC.line} opacity={0.06}>
          {BLOTS.map(([bx, by, rx, ry], i) => (
            <ellipse key={i} cx={bx} cy={by} rx={rx} ry={ry} />
          ))}
        </g>

        {/* 遠景の陸 (沈めて描く) */}
        {FAR_LANDS.map((p, i) => (
          <path key={`f${i}`} d={poly(p)} fill={MC.landFar} stroke={KRP.ink}
            strokeWidth={3} strokeLinejoin="round" opacity={0.72} />
        ))}

        {/* 本体の陸 */}
        <path d={poly(EURASIA)} fill={MC.land} stroke={KRP.ink} strokeWidth={5} strokeLinejoin="round" />
        <path d={poly(AFRICA)} fill={MC.land} stroke={KRP.ink} strokeWidth={5} strokeLinejoin="round" />
        {EU_ISLANDS.map((p, i) => (
          <path key={`e${i}`} d={poly(p)} fill={MC.land} stroke={KRP.ink}
            strokeWidth={4} strokeLinejoin="round" />
        ))}

        {/* 陸の中の記号 (陸でクリップして海にはみ出させない) */}
        <defs>
          <clipPath id="ib5wmLand">
            <path d={poly(EURASIA)} />
            <path d={poly(AFRICA)} />
            {EU_ISLANDS.map((p, i) => <path key={i} d={poly(p)} />)}
          </clipPath>
        </defs>
        <g clipPath="url(#ib5wmLand)" opacity={drawn}>
          {/* 砂漠の点 */}
          <g fill={MC.line} opacity={0.3}>
            {DESERTS.map(([lon, lat], i) => {
              const [x, y] = iwxy(lon, lat);
              return (
                <g key={i}>
                  <circle cx={x} cy={y} r={2.6} />
                  <circle cx={x + 9} cy={y + 6} r={2.2} />
                  <circle cx={x - 7} cy={y + 8} r={2.2} />
                </g>
              );
            })}
          </g>
          {/* 山脈 */}
          <g stroke={MC.line} strokeWidth={3.2} fill="none" strokeLinecap="round" opacity={0.75}>
            {RANGES.map(([lon, lat], i) => {
              const [x, y] = iwxy(lon, lat);
              const h = 1 + Math.sin(f / 19 + i) * 0.04;
              return (
                <g key={i} transform={`translate(${x} ${y}) scale(1 ${h})`}>
                  <path d="M -13 0 L 0 -15 L 13 0" />
                  <path d="M 7 0 L 18 -11 L 28 0" />
                </g>
              );
            })}
          </g>
        </g>

        {/* 日本 (出発点。少し色を変えて「こちら側」だと分かるようにする) */}
        {JAPAN.map((p, i) => (
          <path key={`j${i}`} d={poly(p, JP_DLON, JP_DLAT)} fill="#D9C08C" stroke={KRP.ink}
            strokeWidth={4} strokeLinejoin="round" />
        ))}

        {/* ギリシャ (到着点の国。塗りを一段明るくして目で拾えるようにする) */}
        <g opacity={clamp01(seg(f, 10, 26))}>
          <path
            d={line([
              [23.7, 40.6], [23.4, 38.0], [23.1, 36.4], [21.3, 37.6], [20.7, 38.9], [22.4, 40.2], [23.7, 40.6],
            ])}
            fill={MC.lamp}
            fillOpacity={0.42}
            stroke={MC.beni}
            strokeWidth={3.5}
            strokeLinejoin="round"
          />
        </g>

        {/* 到着点で起きる「大事件」の波紋 */}
        <g opacity={land}>
          {[0, 1, 2].map((i) => {
            const t = clamp01(seg(f, 22 + i * 5, 40 + i * 5));
            return (
              <circle key={i} cx={ax} cy={ay} r={30 + t * (120 + i * 46)} fill="none"
                stroke={MC.beni} strokeWidth={5 - i} opacity={(1 - t) * 0.85} />
            );
          })}
          <circle cx={ax} cy={ay} r={170} fill={MC.lamp} opacity={0.16 * land} />
          <circle cx={ax} cy={ay} r={96} fill={MC.lamp} opacity={0.2 * land} />
        </g>

        {/* 航路の弧 (江戸 → アテネ。f に合わせて出発点から伸びる)。
            pathLength で弧の長さを ROUTE_LEN に正規化してあるので、
            弧の実長を数えなくても strokeDashoffset が素直に 0→100% になる */}
        <g fill="none" strokeLinecap="round">
          {/* 影 */}
          <path
            d={`M ${ex} ${ey} C ${cx1} ${cy1} ${cx2} ${cy2} ${ax} ${ay}`}
            stroke="#6E5F42" strokeWidth={15} opacity={0.26}
            pathLength={ROUTE_LEN}
            strokeDasharray={ROUTE_LEN} strokeDashoffset={ROUTE_LEN * (1 - route)}
            transform="translate(4 7)"
          />
          <path
            d={`M ${ex} ${ey} C ${cx1} ${cy1} ${cx2} ${cy2} ${ax} ${ay}`}
            stroke={MC.nokon} strokeWidth={11}
            pathLength={ROUTE_LEN}
            strokeDasharray={ROUTE_LEN} strokeDashoffset={ROUTE_LEN * (1 - route)}
          />
        </g>
        {/* 弧の上を流れる山形の印 (アテネ側へ送るので向きが分かる)。
            引かれ終わった区間だけに置くので、弧の先より先には出ない */}
        <g stroke={MC.paper} strokeWidth={4} fill="none" strokeLinecap="round" opacity={0.8}>
          {Array.from({ length: 11 }).map((_, i) => {
            const t = ((i / 11 + (f / 150) % (1 / 11)) % 1) * 0.98 + 0.01;
            if (t > route) return null;
            const p = bez(t);
            return (
              <g key={i} transform={`translate(${p.px} ${p.py}) rotate(${p.rot})`}>
                <path d="M -9 -9 L 2 0 L -9 9" />
              </g>
            );
          })}
        </g>
        {/* 弧の先端の矢印 */}
        <g transform={`translate(${head.px} ${head.py}) rotate(${head.rot})`}>
          <polygon points="0,0 -40,-24 -34,0 -40,24"
            fill={MC.nokon} stroke={KRP.ink} strokeWidth={3.5} />
        </g>
      </g>

      {/* 出発点と到着点の旗 (紙の外にはみ出してよいので clip の外に置く) */}
      <FlagPin x={ex} y={ey} t={clamp01(seg(f, 2, 12))} color={MC.nokon} wave={f / 7} />
      <FlagPin x={ax} y={ay} t={clamp01(seg(f, 18, 30))} color={MC.beni} wave={f / 6} mark="star" />

      {/* 地名の札 (出発: 江戸 / 到着: アテネ) */}
      <MapLabel x={ex - 40} y={ey + 92} text="江戸" t={clamp01(seg(f, 6, 18))} size={40} />
      <MapLabel x={ax + 16} y={ay + 112} text="アテネ" t={clamp01(seg(f, 24, 38))} size={40} color={MC.beni} />

      {/* 古地図の縁 */}
      <rect x={SHEET.x + 6} y={SHEET.y + 6} width={SHEET.w - 12} height={SHEET.h - 12}
        fill="none" stroke={KRP.ink} strokeWidth={7} />
    </g>
  );
};
