const poly = (pts: LL[]): string =>
  "M " +
  pts
    .map(([lon, lat]) => {
      const [x, y] = ib2jxy(lon, lat);
      return `${x.toFixed(1)} ${y.toFixed(1)}`;
    })
    .join(" L ") +
  " Z";

