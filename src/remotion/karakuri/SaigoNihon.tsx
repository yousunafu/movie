export type LL = [number, number];
export type Proj = (p: LL) => [number, number];

// 正距円筒 (緯度 latRef で横を縮める)。lon0/lat0 の点が (x0, y0) に来る。k = 緯度1度あたりのpx
export const mkProj = (o: { lon0: number; lat0: number; x0: number; y0: number; k: number; latRef?: number }): Proj => {
  const c = Math.cos(((o.latRef ?? o.lat0) * Math.PI) / 180);
  return ([lon, lat]) => [o.x0 + (lon - o.lon0) * o.k * c, o.y0 - (lat - o.lat0) * o.k];
};

// 閉じた輪郭を Catmull-Rom で滑らかな3次ベジェにする (筆で描いた海岸線らしく)
export const smoothPath = (pts: LL[], P: Proj, closed = true, tension = 0.5): string => {
  const q = pts.map(P);
  const n = q.length;
  if (n < 3) return "";
  const at = (i: number) => (closed ? q[(i + n) % n] : q[Math.max(0, Math.min(n - 1, i))]);
  let d = `M ${q[0][0].toFixed(1)} ${q[0][1].toFixed(1)}`;
  const last = closed ? n : n - 1;
  for (let i = 0; i < last; i++) {
    const p0 = at(i - 1), p1 = at(i), p2 = at(i + 1), p3 = at(i + 2);
    const t = tension / 3;
    const c1x = p1[0] + (p2[0] - p0[0]) * t, c1y = p1[1] + (p2[1] - p0[1]) * t;
    const c2x = p2[0] - (p3[0] - p1[0]) * t, c2y = p2[1] - (p3[1] - p1[1]) * t;
    d += ` C ${c1x.toFixed(1)} ${c1y.toFixed(1)} ${c2x.toFixed(1)} ${c2y.toFixed(1)} ${p2[0].toFixed(1)} ${p2[1].toFixed(1)}`;
  }
  return closed ? d + " Z" : d;
};

