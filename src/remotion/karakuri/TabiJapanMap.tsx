// ===== 折れ線を途中まで引く (t=0..1) =====
const screenPts = (pts: LL[]) => pts.map(([lo, la]) => tjmapXY(lo, la));

export const tjPartial = (pts: LL[], t: number): string => {
  if (t <= 0) return "";
  const xy = screenPts(pts);
  const segs: number[] = [];
  let total = 0;
  for (let i = 1; i < xy.length; i++) {
    const d = Math.hypot(xy[i][0] - xy[i - 1][0], xy[i][1] - xy[i - 1][1]);
    segs.push(d);
    total += d;
  }
  const want = total * Math.min(t, 1);
  const out = [`M ${xy[0][0].toFixed(1)} ${xy[0][1].toFixed(1)}`];
  let acc = 0;
  for (let i = 1; i < xy.length; i++) {
    const d = segs[i - 1];
    if (acc + d <= want || d === 0) {
      out.push(`L ${xy[i][0].toFixed(1)} ${xy[i][1].toFixed(1)}`);
      acc += d;
    } else {
      const r = (want - acc) / d;
      out.push(
        `L ${(xy[i - 1][0] + (xy[i][0] - xy[i - 1][0]) * r).toFixed(1)} ` +
        `${(xy[i - 1][1] + (xy[i][1] - xy[i - 1][1]) * r).toFixed(1)}`
      );
      break;
    }
  }
  return out.join(" ");
};

// 先端の座標 (伸びていく点を置く用)
export const tjHead = (pts: LL[], t: number): [number, number] => {
  const xy = screenPts(pts);
  if (t <= 0) return xy[0];
  const segs: number[] = [];
  let total = 0;
  for (let i = 1; i < xy.length; i++) {
    const d = Math.hypot(xy[i][0] - xy[i - 1][0], xy[i][1] - xy[i - 1][1]);
    segs.push(d);
    total += d;
  }
  const want = total * Math.min(t, 1);
  let acc = 0;
  for (let i = 1; i < xy.length; i++) {
    const d = segs[i - 1];
    if (acc + d >= want && d > 0) {
      const r = (want - acc) / d;
      return [
        xy[i - 1][0] + (xy[i][0] - xy[i - 1][0]) * r,
        xy[i - 1][1] + (xy[i][1] - xy[i - 1][1]) * r,
      ];
    }
    acc += d;
  }
  return xy[xy.length - 1];
};

