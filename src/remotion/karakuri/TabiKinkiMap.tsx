// 経路を 0→1 で辿ったときの画面座標 (弧長で等速)
export const kmapPointAt = (pts: LL[], t: number): [number, number] => {
  const xy = pts.map(([lo, la]) => kmapXY(lo, la));
  const segs: number[] = [];
  let total = 0;
  for (let i = 1; i < xy.length; i++) {
    const d = Math.hypot(xy[i][0] - xy[i - 1][0], xy[i][1] - xy[i - 1][1]);
    segs.push(d);
    total += d;
  }
  let want = Math.min(Math.max(t, 0), 1) * total;
  for (let i = 0; i < segs.length; i++) {
    if (want <= segs[i] || i === segs.length - 1) {
      const r = segs[i] > 0 ? Math.min(want / segs[i], 1) : 0;
      return [xy[i][0] + (xy[i + 1][0] - xy[i][0]) * r, xy[i][1] + (xy[i + 1][1] - xy[i][1]) * r];
    }
    want -= segs[i];
  }
  return xy[xy.length - 1];
};

